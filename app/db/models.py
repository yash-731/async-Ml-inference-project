"""ORM models.

A single `jobs` table carries both metadata and results. A separate
dead-letter table would isolate the failure path, but it duplicates the schema
and buys nothing at this scale, so permanent failure is a status value instead.
"""

from __future__ import annotations

import enum
import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import DateTime, Enum, Index, Integer, String, Text, func
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.dialects.postgresql import UUID as PGUUID
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class JobStatus(enum.StrEnum):
    """Lifecycle of a forecasting job.

    `failed` and `dead_letter` are deliberately distinct:
      failed      -> we know why it will never succeed (bad input data).
                     Retrying is pointless; the user must fix the upload.
      dead_letter -> a transient-looking error survived every retry, or an
                     unexpected exception escaped. Needs a human to look.
    """

    pending = "pending"
    running = "running"
    success = "success"
    failed = "failed"
    dead_letter = "dead_letter"


TERMINAL_STATUSES = frozenset({JobStatus.success, JobStatus.failed, JobStatus.dead_letter})


class Job(Base):
    __tablename__ = "jobs"

    id: Mapped[uuid.UUID] = mapped_column(
        PGUUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )

    # SHA-256 of the uploaded bytes. The UNIQUE constraint -- not the
    # application's pre-check -- is what actually makes submission idempotent:
    # two concurrent identical uploads cannot both insert.
    idempotency_key: Mapped[str] = mapped_column(String(64), nullable=False, unique=True)

    # native_enum=False + create_constraint=True -> VARCHAR with a CHECK.
    # Keeps DB-level validation without the ALTER TYPE dance that a native
    # PostgreSQL enum forces on every future migration that adds a status.
    # create_constraint defaults to False, so leaving it off would mean no
    # database-level validation at all.
    status: Mapped[JobStatus] = mapped_column(
        Enum(
            JobStatus,
            native_enum=False,
            create_constraint=True,
            length=16,
            name="job_status",
            values_callable=lambda e: [m.value for m in e],
        ),
        nullable=False,
        default=JobStatus.pending,
    )

    model_name: Mapped[str] = mapped_column(String(64), nullable=False)
    horizon: Mapped[int] = mapped_column(Integer, nullable=False)

    original_filename: Mapped[str] = mapped_column(String(255), nullable=False)
    storage_path: Mapped[str] = mapped_column(String(512), nullable=False)
    row_count: Mapped[int | None] = mapped_column(Integer, nullable=True)

    result: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True)
    error_type: Mapped[str | None] = mapped_column(String(64), nullable=True)
    error_message: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Mirrored from Celery purely so the API can report progress without
    # querying the broker. Celery remains the authority on scheduling.
    retry_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    max_retries: Mapped[int] = mapped_column(Integer, nullable=False, default=3)
    celery_task_id: Mapped[str | None] = mapped_column(String(64), nullable=True)

    # Generated by API middleware, carried into the worker's log context.
    correlation_id: Mapped[str] = mapped_column(String(64), nullable=False)

    # clock_timestamp(), not now(). PostgreSQL's now()/CURRENT_TIMESTAMP is
    # fixed at transaction start, so every row inserted in one transaction
    # would share a created_at and the "newest first" listing would fall back
    # to tie-breaking on a random UUID. clock_timestamp() reads the actual
    # wall clock per statement, which is what an insert-time audit column
    # should record.
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.clock_timestamp()
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.clock_timestamp(),
        onupdate=func.clock_timestamp(),
    )
    started_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    __table_args__ = (
        Index("ix_jobs_idempotency_key", "idempotency_key", unique=True),
        Index("ix_jobs_status", "status"),
        # Matches the default list ordering (newest first).
        Index("ix_jobs_created_at_desc", created_at.desc()),
    )

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"<Job id={self.id} status={self.status.value}>"

    @property
    def is_terminal(self) -> bool:
        return self.status in TERMINAL_STATUSES
